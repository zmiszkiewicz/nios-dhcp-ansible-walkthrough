#!/usr/bin/env python3
"""Turn the baseline's Terraform outputs into the Ansible inventory and lab state.

  python3 make_inventory.py [--terraform-dir DIR] [--from-json FILE]

Writes:
  ansible/inventory/lab.yml   the wake-up servers as a WinRM (HTTPS) group
  .state/lab.json             addresses the shell scripts read (simulator, key, ...)

The inventory holds no password: ansible_password is an environment lookup, so
set WINDOWS_ADMIN_PASSWORD before running a playbook. Each host also carries
wakeup_private_ip, the address NIOS knows it by (the WakeUp_Server extensible
attribute, or the <first three octets>.111 convention). The control node
connects to the public address; the playbooks use wakeup_private_ip to match a
scope to the right inventory host.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

from nios_wapi import save_state

REPO_ROOT = Path(__file__).resolve().parent.parent
INVENTORY = REPO_ROOT / "ansible" / "inventory" / "lab.yml"


def terraform_outputs(terraform_dir):
    result = subprocess.run(
        ["terraform", f"-chdir={terraform_dir}", "output", "-json"],
        capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise SystemExit(f"terraform output failed in {terraform_dir}:\n{result.stderr.strip()}")
    return {key: value["value"] for key, value in json.loads(result.stdout).items()}


def render_inventory(outputs):
    lines = [
        "---",
        "# Generated by scripts/make_inventory.py from the baseline Terraform outputs.",
        "# Not committed. ansible_password comes from the environment.",
        "all:",
        "  children:",
        "    wakeup:",
        "      hosts:",
    ]
    for name, server in sorted(outputs["wakeup_servers"].items()):
        lines += [
            f"        {name}:",
            f"          ansible_host: {server['public_ip']}",
            f"          wakeup_private_ip: {server['private_ip']}",
            f"          branch: {server['branch']}",
        ]
    lines += [
        "      vars:",
        "        ansible_connection: winrm",
        "        ansible_port: 5986",
        "        ansible_winrm_scheme: https",
        "        ansible_winrm_transport: basic",
        "        ansible_winrm_server_cert_validation: ignore",
        "        ansible_user: \"{{ lookup('ansible.builtin.env', 'WINDOWS_ADMIN_USER') | default('Administrator', true) }}\"",
        "        ansible_password: \"{{ lookup('ansible.builtin.env', 'WINDOWS_ADMIN_PASSWORD') }}\"",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--terraform-dir", default=str(REPO_ROOT / "terraform" / "00-baseline"))
    parser.add_argument("--from-json", help="read outputs from a saved `terraform output -json` file (tests)")
    args = parser.parse_args()

    if args.from_json:
        outputs = {k: v["value"] for k, v in json.loads(Path(args.from_json).read_text()).items()}
    else:
        outputs = terraform_outputs(args.terraform_dir)

    INVENTORY.parent.mkdir(parents=True, exist_ok=True)
    INVENTORY.write_text(render_inventory(outputs))
    save_state("lab", {
        "gm_public_ip": outputs["gm_public_ip"],
        "sim_public_ip": outputs["sim_public_ip"],
        "ssh_key_path": outputs["ssh_key_path"],
        "wakeup_servers": outputs["wakeup_servers"],
        "branch_relays": outputs["branch_relays"],
    })
    print(f"  [OK] wrote {INVENTORY.relative_to(REPO_ROOT)} ({len(outputs['wakeup_servers'])} wake-up servers)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
